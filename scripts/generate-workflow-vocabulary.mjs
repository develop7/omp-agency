import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { join } from "node:path";

const root = join(fileURLToPath(new URL("..", import.meta.url)));
const manifestPath = join(root, "skills/do/workflow-manifest.json");
const outputs = {
  pure: join(root, "pure/src/Agency/Scripts/Do/WorkflowVocabulary.purs"),
  typescript: join(root, "src/workflow-vocabulary.ts"),
};

function fail(message) {
  throw new Error(`workflow manifest: ${message}`);
}

function readManifest() {
  let manifest;
  try {
    manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  } catch (error) {
    fail(`cannot parse ${manifestPath}: ${error instanceof Error ? error.message : String(error)}`);
  }

  if (manifest === null || typeof manifest !== "object" || Array.isArray(manifest)) {
    fail("must be an object");
  }
  if (!Array.isArray(manifest.steps) || manifest.steps.length === 0) {
    fail("steps must be a non-empty array");
  }
  if (manifest.steps.some((step) => typeof step !== "string" || step === "")) {
    fail("steps must contain only non-empty strings");
  }
  if (new Set(manifest.steps).size !== manifest.steps.length) {
    fail("steps must not contain duplicates");
  }
  if (manifest.entryPoints === null || typeof manifest.entryPoints !== "object" || Array.isArray(manifest.entryPoints)) {
    fail("entryPoints must be an object");
  }

  const entryPoints = Object.entries(manifest.entryPoints);
  if (entryPoints.length === 0) {
    fail("entryPoints must not be empty");
  }
  for (const [id, target] of entryPoints) {
    if (id === "" || typeof target !== "string" || !manifest.steps.includes(target)) {
      fail(`entry point ${JSON.stringify(id)} must target a declared step`);
    }
  }
  if (manifest.entryPoints.default === undefined) {
    fail("entryPoints must define default");
  }

  return { steps: manifest.steps, entryPoints: entryPoints.map(([id]) => id) };
}

function pureArray(values) {
  return values.map((value, index) => `${index === 0 ? "  [" : "  ,"} ${JSON.stringify(value)}`).join("\n") + "\n  ]";
}

function renderPure(manifest) {
  return `-- Generated by scripts/generate-workflow-vocabulary.mjs from skills/do/workflow-manifest.json. Do not edit.\nmodule Agency.Scripts.Do.WorkflowVocabulary\n  ( entryPoints\n  , workflowSteps\n  ) where\n\nimport Prelude\n\nentryPoints :: Array String\nentryPoints =\n${pureArray(manifest.entryPoints)}\n\nworkflowSteps :: Array String\nworkflowSteps =\n${pureArray(manifest.steps)}\n`;
}

function renderTypeScript(manifest) {
  return `// Generated by scripts/generate-workflow-vocabulary.mjs from skills/do/workflow-manifest.json. Do not edit.\nexport const workflowEntryPoints = ${JSON.stringify(manifest.entryPoints)} as const;\n`;
}

const manifest = readManifest();
const generated = {
  [outputs.pure]: renderPure(manifest),
  [outputs.typescript]: renderTypeScript(manifest),
};
const check = process.argv.includes("--check");

for (const [path, content] of Object.entries(generated)) {
  if (check) {
    let current;
    try {
      current = readFileSync(path, "utf8");
    } catch (error) {
      fail(`generated file is missing: ${path}`);
    }
    if (current !== content) {
      fail(`generated file is stale: ${path}; run 'node scripts/generate-workflow-vocabulary.mjs'`);
    }
  } else {
    writeFileSync(path, content, "utf8");
  }
}
